"""S2-2D: Camera fixture clips validation tests.

These tests validate that the generated fixture clips are readable and have
expected properties. The clips are used for S4/S5 validation.

Fixtures generated by scripts/generate_fixtures.py:
- single_person.mp4: one person walking across frame (60 frames)
- two_persons_crossing.mp4: two people crossing paths (90 frames)
- partial_occlusion.mp4: person briefly occluded by object (90 frames)
- re_entry.mp4: person leaves and re-enters zone (120 frames)
"""

from __future__ import annotations

import cv2
import pytest

from pathlib import Path

FIXTURE_DIR = Path(__file__).parent / "fixtures"


class TestFixtures:
    """Validate that the generated fixture clips are readable and have expected properties."""

    @pytest.mark.parametrize("name,expected_frames", [
        ("single_person.mp4", 60),
        ("two_persons_crossing.mp4", 90),
        ("partial_occlusion.mp4", 90),
        ("re_entry.mp4", 120),
    ])
    def test_fixture_readable(self, name: str, expected_frames: int):
        path = FIXTURE_DIR / name
        assert path.exists(), f"Fixture {name} not found"

        cap = cv2.VideoCapture(str(path))
        assert cap.isOpened(), f"Could not open {name}"

        frame_count = 0
        while True:
            ret, frame = cap.read()
            if not ret:
                break
            frame_count += 1

        cap.release()

        assert frame_count == expected_frames, f"{name}: expected {expected_frames} frames, got {frame_count}"

    @pytest.mark.parametrize("name,expected_fps,expected_width,expected_height", [
        ("single_person.mp4", 30.0, 640, 480),
        ("two_persons_crossing.mp4", 30.0, 640, 480),
        ("partial_occlusion.mp4", 30.0, 640, 480),
        ("re_entry.mp4", 30.0, 640, 480),
    ])
    def test_fixture_properties(self, name: str, expected_fps: float, expected_width: int, expected_height: int):
        path = FIXTURE_DIR / name
        assert path.exists()

        cap = cv2.VideoCapture(str(path))
        assert cap.isOpened()

        fps = cap.get(cv2.CAP_PROP_FPS)
        width = int(cap.get(cv2.CAP_PROP_FRAME_WIDTH))
        height = int(cap.get(cv2.CAP_PROP_FRAME_HEIGHT))

        cap.release()

        assert abs(fps - expected_fps) < 1.0, f"{name}: expected {expected_fps} fps, got {fps}"
        assert width == expected_width, f"{name}: expected width {expected_width}, got {width}"
        assert height == expected_height, f"{name}: expected height {expected_height}, got {height}"